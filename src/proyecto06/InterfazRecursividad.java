    // ================================================================
// FACTORIAL
// ================================================================
private void ejecutarFactorial(int n) {
    if (n > 20) {
        areaResultados.append("⚠️  Advertencia: n > 20 puede provocar desbordamiento en long.\n\n");
    }

    ModuloRecursividad.llamadasFactorialRec = 0;
    long inicioRec = System.nanoTime();
    long resRec;
    try {
        resRec = ModuloRecursividad.factorialRecursivo(n);
    } catch (StackOverflowError e) {
        areaResultados.append("❌ StackOverflowError en factorial recursivo con n=" + n + "\n");
        return;
    }
    long finRec = System.nanoTime();

    long inicioIt = System.nanoTime();
    long resIt = ModuloRecursividad.factorialIterativo(n);
    long finIt = System.nanoTime();

    areaResultados.append(String.format("=== FACTORIAL(%d) ===%n", n));
    areaResultados.append(String.format("Recursivo -> %,d  | llamadas: %,d | %.3f ms%n",
            resRec, ModuloRecursividad.llamadasFactorialRec, (finRec - inicioRec) / 1_000_000.0));
    areaResultados.append(String.format("Iterativo -> %,d  | llamadas: 0 (iterativo) | %.3f ms%n%n",
            resIt, (finIt - inicioIt) / 1_000_000.0));
    lblEstado.setText("Factorial calculado.");
}

// ================================================================
// FIBONACCI
// ================================================================
private void ejecutarFibonacci(int n) {
    if (n > 45) {
        areaResultados.append("⚠️  Advertencia: n > 45 hace que Fibonacci recursivo tarde demasiado.\n\n");
    }

    ModuloRecursividad.llamadasFibonacciRec = 0;
    long inicioRec = System.nanoTime();
    long resRec;
    try {
        resRec = ModuloRecursividad.fibonacciRecursivo(n);
    } catch (StackOverflowError e) {
        areaResultados.append("❌ StackOverflowError en fibonacci recursivo con n=" + n + "\n");
        return;
    }
    long finRec = System.nanoTime();

    long inicioIt = System.nanoTime();
    long resIt = ModuloRecursividad.fibonacciIterativo(n);
    long finIt = System.nanoTime();

    areaResultados.append(String.format("=== FIBONACCI(%d) ===%n", n));
    areaResultados.append(String.format("Recursivo -> %,d  | llamadas: %,d | %.3f ms%n",
            resRec, ModuloRecursividad.llamadasFibonacciRec, (finRec - inicioRec) / 1_000_000.0));
    areaResultados.append(String.format("Iterativo -> %,d  | llamadas: 0 (iterativo) | %.3f ms%n%n",
            resIt, (finIt - inicioIt) / 1_000_000.0));
    lblEstado.setText("Fibonacci calculado.");
}

// ================================================================
// TORRES DE HANOI
// ================================================================
private void ejecutarHanoi(int n) {
    if (n < 1) {
        areaResultados.append("⚠️  El número de discos debe ser >= 1.\n");
        return;
    }
    if (n > 20) {
        areaResultados.append("⚠️  Advertencia: n > 20 generará demasiados movimientos (2^n - 1).\n\n");
    }

    ModuloRecursividad.movimientosHanoi = 0;
    areaResultados.append(String.format("=== TORRES DE HANOI (n=%d) ===%n", n));

    // Redirigir salida de System.out al área de texto para no perder los movimientos
    java.io.ByteArrayOutputStream baos = new java.io.ByteArrayOutputStream();
    java.io.PrintStream ps = new java.io.PrintStream(baos);
    java.io.PrintStream old = System.out;
    System.setOut(ps);

    long inicio = System.nanoTime();
    ModuloRecursividad.hanoiRecursivo(n, 'A', 'B', 'C');
    long fin = System.nanoTime();

    System.out.flush();
    System.setOut(old);

    areaResultados.append(baos.toString());
    areaResultados.append(String.format("%nTotal de movimientos: %,d%n", ModuloRecursividad.movimientosHanoi));
    areaResultados.append(String.format("Tiempo: %.3f ms%n%n", (fin - inicio) / 1_000_000.0));
    lblEstado.setText("Hanoi resuelto.");
}
