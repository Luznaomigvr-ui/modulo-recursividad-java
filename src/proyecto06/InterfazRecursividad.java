    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed

    areaResultados.setText("");
    String algoritmo = comboAlgoritmo.getSelectedItem().toString();
    String textoN = txtN.getText().trim();

    if (textoN.isEmpty()) {
        areaResultados.append("⚠️  Debes ingresar un valor para n.\n");
        return;
    }

    int n;
    try {
        n = Integer.parseInt(textoN);
    } catch (NumberFormatException e) {
        areaResultados.append("⚠️  n debe ser un número entero.\n");
        return;
    }

    if (n < 0) {
        areaResultados.append("⚠️  n no puede ser negativo.\n");
        return;
    }

    switch (algoritmo) {
        case "Factorial":        ejecutarFactorial(n);   break;
        case "Fibonacci":        ejecutarFibonacci(n);   break;
        case "Torres de Hanoi":  ejecutarHanoi(n);       break;
    }

    }//GEN-LAST:event_btnCalcularActionPerformed

    private void btnStackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStackActionPerformed
       
    areaResultados.setText("");
    areaResultados.append("=== PRUEBA DE DESBORDAMIENTO DE PILA ===\n");
    areaResultados.append("Incrementando recursión hasta StackOverflowError...\n\n");

    long inicio = System.nanoTime();
    int profundidad = ModuloRecursividad.probarStackOverflow();
    long fin = System.nanoTime();

    areaResultados.append(String.format("Profundidad máxima alcanzada: %,d llamadas%n", profundidad));
    areaResultados.append(String.format("Tiempo antes del desbordamiento: %.3f ms%n", (fin - inicio) / 1_000_000.0));
    areaResultados.append("\n");
    lblEstado.setText("Prueba de StackOverflow completada.");
    }//GEN-LAST:event_btnStackActionPerformed

